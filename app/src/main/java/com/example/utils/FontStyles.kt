        "Circled" to buildLookupTableFromList(CIRCLED_ARR),
        "Squared" to buildLookupTableFromList(SQUARED_ARR),
        "Fullwidth" to buildLookupTableFromCodePoints(FULLWIDTH_MAP),
        "Small Caps" to buildLookupTableFromCodePoints(SMALL_CAPS_MAP)
    )

    fun apply(text: String, style: String): String {
        if (style == "Default" || text.isEmpty()) return text
        val table = styleTables[style] ?: return text
        val sb = StringBuilder(text.length * 2)
        for (i in 0 until text.length) {
            val ch = text[i]
            val code = ch.code
            if (code in 0..127) {
                val mapped = table[code]
                if (mapped != null) {
                    sb.append(mapped)
                } else {
                    sb.append(ch)
                }
            } else {
                sb.append(ch)
            }
        }
        return sb.toString()
    }
