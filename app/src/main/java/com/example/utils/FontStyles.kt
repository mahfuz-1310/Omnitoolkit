    private fun buildLookupTableFromCodePoints(mapStr: String): Array<String?> {
        val table = arrayOfNulls<String>(128)
        val codePoints = ArrayList<String>(NORMAL.length)
        var i = 0
        while (i < mapStr.length) {
            val codePoint = mapStr.codePointAt(i)
            codePoints.add(String(Character.toChars(codePoint)))
            i += Character.charCount(codePoint)
        }
        for (idx in NORMAL.indices) {
            val ch = NORMAL[idx]
            if (idx < codePoints.size && ch.code < 128) {
                table[ch.code] = codePoints[idx]
            }
        }
        return table
    }

    private fun buildLookupTableFromList(list: List<String>): Array<String?> {
        val table = arrayOfNulls<String>(128)
        for (idx in NORMAL.indices) {
            val ch = NORMAL[idx]
            if (idx < list.size && ch.code < 128) {
                table[ch.code] = list[idx]
            }
        }
        return table
    }

    private val styleTables: Map<String, Array<String?>> = mapOf(
        "Bold" to buildLookupTableFromCodePoints(BOLD_MAP),
        "Italic" to buildLookupTableFromCodePoints(ITALIC_MAP),
